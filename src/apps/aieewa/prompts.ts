/** 채점 프롬프트의 사용자 메시지. 문항의 기준 전체를 넣는다. */
export function scoreUser(args: {
  gradeUnit: string
  passage: string
  prompt: string
  conditions: string
  analyticCriteria: string[]
  holisticCriteria: Record<string, string>
  levelAnswers: Record<string, string>
  studentLabel: string
  answer: string
  extraInstruction?: string
}): string {
  const criteria = args.analyticCriteria.map((c, i) => `[분석적 채점 기준 ${i + 1}]\n${c}`).join('\n\n')
  const holistic = (['A', 'B', 'C'] as const)
    .map((level) => `${level} 수준: ${args.holisticCriteria[level] ?? ''}`)
    .join('\n')
  const samples = (['A', 'B', 'C'] as const)
    .map((level) => `${level} 수준 예시 답안:\n${args.levelAnswers[level] ?? ''}`)
    .join('\n\n')

  return `[문항]
단원·학년: ${args.gradeUnit}

예시문:
${args.passage}

평가 문항: ${args.prompt}

조건:
${args.conditions}

[채점 기준]
${criteria}

[총체적 채점 기준]
${holistic}

[성취수준별 예시 답안]
${samples}

[채점할 답안]
학생: ${args.studentLabel}
답안:
${args.answer}
${args.extraInstruction ? `\n[추가 지시]\n${args.extraInstruction}` : ''}`
}
